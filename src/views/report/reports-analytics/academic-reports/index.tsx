      if (filters['report-status'] && statusOf(row) !== filters['report-status']) return false;
      if (filters.grade && overallGradeOf(row)?.grade !== filters.grade) return false;
      if (filters.delivery && deliveryOf(row) !== filters.delivery) return false;
      if (filters['marks-entry'] && marksEntryOf(row) !== filters['marks-entry']) return false;
      if (filters['needs-action'] && !needsActionOf(row)) return false;

