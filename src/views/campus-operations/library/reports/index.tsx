/** The day the template is written as on; every stamp this page writes uses it. */
const TODAY = '31 Jul 2026';
const NOW = '09:00 AM';

const monthNames = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** "01-07-2026" + "31-07-2026" → "01 – 31 Jul 2026", the template's own shape. */
const rangeLabel = (from: string, to: string): string => {
  const [d1, m1, y1] = from.split('-');
  const [d2, m2, y2] = to.split('-');
  const mon1 = monthNames[Number(m1) - 1] ?? m1;
  const mon2 = monthNames[Number(m2) - 1] ?? m2;
  if (!d1 || !d2) return `${from} – ${to}`;
  if (m1 === m2 && y1 === y2) return `${d1} – ${d2} ${mon2} ${y2}`;
  if (y1 === y2) return `${d1} ${mon1} – ${d2} ${mon2} ${y2}`;
  return `${d1} ${mon1} ${y1} – ${d2} ${mon2} ${y2}`;
};

/** The Schedule dialog's Run On select, phrased the way the panel prints it. */
const runOnPhrase = (runOn: string): string => {
  if (runOn === '1st of the period') return 'on the 1st';
  if (runOn === '15th of the month') return 'on the 15th';
  return 'on the last day';
};

