import { useCallback, useMemo, useState } from 'react';
import Modal from '@components/ui/Modal';
import Offcanvas from '@components/ui/Offcanvas';
import ToastStack from '@components/ui/ToastStack';
import { ActionLink, PageHeader, WorkspaceShell, useWorkspace } from '@components/workspace';
import type {
  ColumnDef, FilterField, QuickFilter, SavedView, SortOption, WorkspaceMenu,
} from '@components/workspace';
import { all_routes } from '@/routes/all_routes';
import { useToasts } from '@hooks/useToasts';
import type { TaxReport, TaxStatus } from './data/taxReports.data';
import {
  filingPeriodOptions, financialYearOptions, generatedByOptions, money, returnFormOptions,
  statusBadge, statusOptions, statusPill, taxReportCards, taxReports as initialRows,
  taxTypeOptions,
} from './data/taxReports.data';

const routes = all_routes;

/** Financial Year opens pre-applied — the template renders its chip on load. */
const filterFields: FilterField[] = [
  { id: 'tax-type', label: 'Tax Type', kind: 'select', chipLabel: 'Tax', options: taxTypeOptions },
  { id: 'financial-year', label: 'Financial Year', kind: 'select', chipLabel: 'Financial Year', options: financialYearOptions, initialValue: '2026 – 2027' },
  { id: 'filing-period', label: 'Filing Period', kind: 'select', chipLabel: 'Period', options: filingPeriodOptions },
  { id: 'report-status', label: 'Report Status', kind: 'select', chipLabel: 'Status', options: statusOptions },
  { id: 'return-form', label: 'Return Form', kind: 'select', chipLabel: 'Form', options: returnFormOptions },
  { id: 'generated-by', label: 'Generated By', kind: 'select', chipLabel: 'By', options: generatedByOptions },
  { id: 'date-from', label: 'Date From', kind: 'date', chipLabel: 'From', placeholder: '01-04-2026' },
  { id: 'date-to', label: 'Date To', kind: 'date', chipLabel: 'To', placeholder: '31-07-2026' },
];

/** Counts are the template's school-wide figures across 72 tax reports. */
const savedViews: SavedView[] = [
  { id: 'all', label: 'All Tax Reports', icon: 'ti ti-layout-list', count: 72 },
  { id: 'Pending Filing', label: 'Pending Filing', icon: 'ti ti-clock', count: 6 },
  { id: 'Overdue', label: 'Overdue Filings', icon: 'ti ti-alert-triangle', count: 2 },
  { id: 'Filed', label: 'Filed Returns', icon: 'ti ti-shield-check', count: 48 },
  { id: 'Archived', label: 'Archived', icon: 'ti ti-folder', count: 14 },
];

/**
 * The rail mixes statuses with tax types — the template's own grouping. The
 * last two narrow by Tax Type, the first three by Report Status.
 */
const quickFilters: QuickFilter[] = [
  { id: 'Pending Filing', label: 'Pending Filing', icon: 'ti ti-clock', count: 6 },
  { id: 'Overdue', label: 'Overdue', icon: 'ti ti-alert-triangle', count: 2 },
  { id: 'Filed', label: 'Filed', icon: 'ti ti-shield-check', count: 48 },
  { id: 'GST', label: 'GST', icon: 'ti ti-percentage', count: 54 },
  { id: 'TDS', label: 'TDS', icon: 'ti ti-cash', count: 18 },
];

const sortOptions: SortOption[] = [
  { id: 'generated', label: 'Generated date (newest)', icon: 'ti ti-clock' },
  { id: 'amount', label: 'Tax amount', icon: 'ti ti-currency-dollar' },
  { id: 'due', label: 'Filing due date', icon: 'ti ti-calendar-due' },
  { id: 'name', label: 'Report name (A–Z)', icon: 'ti ti-abc' },
  { id: 'type', label: 'Tax type', icon: 'ti ti-category' },
];

type TaxModalId = 'generate' | 'view' | 'export' | 'print' | 'statement' | 'file';

const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
/** Sorts "30 Jul 2026" without a date library; 0 for values that are not dates. */
const dateKey = (value: string): number => {
  const match = value.match(/(\d{1,2}) ([A-Z][a-z]{2}) (\d{4})/);
  if (!match) return 0;
  return Number(match[3]) * 10000 + (months.indexOf(match[2]) + 1) * 100 + Number(match[1]);
};

/** The Filing Due (or Filed On) line from a row's filing panel. */
const dueDateOf = (row: TaxReport): string =>
  row.filing.find((item) => item.label === 'Filing Due' || item.label === 'Filed On')?.value ?? '';

const TaxReports = () => {
  const [rows, setRows] = useState<TaxReport[]>(initialRows);
  const [openMenu, setOpenMenu] = useState<WorkspaceMenu>(null);
  const [activeModal, setActiveModal] = useState<TaxModalId | null>(null);
  const [modalRow, setModalRow] = useState<TaxReport | null>(null);
  const [panelRow, setPanelRow] = useState<TaxReport | null>(null);
  const [generateType, setGenerateType] = useState<string>(taxTypeOptions[0]);
  const [generateForm, setGenerateForm] = useState(returnFormOptions[0]);
  const [exportFormat, setExportFormat] = useState('PDF');
  const [ackNumber, setAckNumber] = useState('');

  const { toasts, push, dismiss } = useToasts();

  const openModal = useCallback((row: TaxReport | null, modal: TaxModalId) => {
    setModalRow(row);
    setActiveModal(modal);
    if (modal === 'file') setAckNumber('');
  }, []);

  const columns = useMemo<ColumnDef<TaxReport>[]>(
    () => [
      {
        id: 'name', label: 'Report Name', toggleable: false, sortable: true,
        render: (row) => (
          <div className="dt-user">
            <span className={`avatar avatar-sm bg-${row.taxTypeTint}-transparent text-${row.taxTypeTint} rounded me-2 flex-shrink-0`}>
              <i className="ti ti-file-text" />
            </span>
            <div>
              <ActionLink className="dt-name" onClick={() => openModal(row, 'view')}>{row.name}</ActionLink>
              <div className="dt-sub">{row.filingPeriod}</div>
            </div>
          </div>
        ),
      },
      {
        id: 'taxType', label: 'Tax Type', sortable: true,
        render: (row) => <span className={`badge badge-soft-${row.taxTypeTint}`}>{row.taxType}</span>,
      },
      { id: 'filingPeriod', label: 'Filing Period', cellClassName: 'fs-13', render: (row) => row.filingPeriod },
      { id: 'financialYear', label: 'Financial Year', cellClassName: 'fs-13', render: (row) => row.financialYear },
      {
        id: 'taxAmount', label: 'Tax Amount', sortable: true, align: 'end', cellClassName: 'fw-medium',
        render: (row) => money(row.taxAmount),
      },
      {
        id: 'generatedBy', label: 'Generated By',
        render: (row) => (
          <>
            <span className="d-block fs-13 fw-medium">{row.generatedBy}</span>
            <span className="fs-12 text-muted">{row.generatedByDept}</span>
          </>
        ),
      },
      {
        id: 'generatedDate', label: 'Generated Date', sortable: true, cellClassName: 'fs-13',
        render: (row) => (
          <>
            {row.generatedDate}
            <span className="d-block fs-12 text-muted">{row.generatedTime}</span>
          </>
        ),
      },
      {
        id: 'status', label: 'Report Status', toggleable: false, sortable: true,
        render: (row) => (
          <>
            <span className={`dt-pill ${statusPill[row.status]}`}>
              <span className="dt-pill-dot" />{row.status}
            </span>
            <span className="fs-12 text-muted d-block mt-1">{row.returnForm}</span>
          </>
        ),
      },
    ],
    [openModal],
  );

  const workspace = useWorkspace<TaxReport>({
    rows, filterFields, columns,
    getId: (row) => row.id,
    search: (row, term) => `${row.name} ${row.filingPeriod} ${row.taxType}`.toLowerCase().includes(term),
    matches: (row, filters) => {
      if (filters['tax-type'] && row.taxType !== filters['tax-type']) return false;
      if (filters['financial-year'] && row.financialYear !== filters['financial-year']) return false;
      if (filters['filing-period'] && !row.filingPeriod.startsWith(filters['filing-period'])) return false;
      if (filters['report-status'] && row.status !== filters['report-status']) return false;
      if (filters['return-form'] && !row.returnForm.startsWith(filters['return-form'])) return false;
      if (filters['generated-by'] && row.generatedBy !== filters['generated-by']) return false;
      return true;
    },
    // The rail mixes statuses and tax types, so a quick filter matches either.
    quickMatch: (row, quick) => !quick || row.status === quick || row.taxType === quick,
    viewMatch: (row, view) => (view === 'all' ? true : row.status === view),
    compare: (a, b, sort) => {
      switch (sort) {
        case 'amount': return b.taxAmount - a.taxAmount || a.name.localeCompare(b.name);
        case 'due': return dateKey(dueDateOf(a)) - dateKey(dueDateOf(b)) || a.name.localeCompare(b.name);
        case 'name': return a.name.localeCompare(b.name);
        case 'type': return a.taxType.localeCompare(b.taxType) || a.name.localeCompare(b.name);
        case 'generated':
        default: return dateKey(b.generatedDate) - dateKey(a.generatedDate) || a.name.localeCompare(b.name);
      }
    },
    defaultSort: 'generated',
    pageSize: 8,
  });

  /* --------------------------------- Actions -------------------------------- */

  const markFiled = useCallback(() => {
    if (!modalRow) return;
    const acknowledgement = ackNumber.trim();
    setRows((current) =>
      current.map((row) =>
        row.id === modalRow.id
          ? {
              ...row,
              status: 'Filed' as TaxStatus,
              filing: row.filing.map((item) =>
                item.label === 'Filing Status'
                  ? { label: 'Filing Status', value: acknowledgement ? `Filed · ${acknowledgement}` : 'Filed' }
                  : item,
              ),
            }
          : row,
      ),
    );
    setActiveModal(null);
    push(`${modalRow.name} marked as filed`);
  }, [ackNumber, modalRow, push]);

  const rowActions = (row: TaxReport) => (
    <div className="dt-actions">
      <ActionLink className="dt-ib" ariaLabel="View tax report" onClick={() => openModal(row, 'view')}>
        <i className="ti ti-eye" />
      </ActionLink>
      {row.status === 'Pending Filing' || row.status === 'Overdue' || row.status === 'Ready' ? (
        <ActionLink className="dt-ib success" ariaLabel="Mark as filed" onClick={() => openModal(row, 'file')}>
          <i className="ti ti-shield-check" />
        </ActionLink>
      ) : null}
      <ActionLink className="dt-ib" ariaLabel="Download tax statement" onClick={() => openModal(row, 'statement')}>
        <i className="ti ti-download" />
      </ActionLink>
      <ActionLink className="dt-ib" ariaLabel="Print tax report" onClick={() => openModal(row, 'print')}>
        <i className="ti ti-printer" />
      </ActionLink>
    </div>
  );

  /* --------------------------------- Panels --------------------------------- */

  const infoList = (items: { label: string; value: string }[]) => (
    <ul className="list-unstyled mb-0">
      {items.map((item, index) => (
        <li
          className={`d-flex justify-content-between py-1 fs-13${index === items.length - 1 ? '' : ' border-bottom'}`}
          key={item.label}
        >
          <span className="text-muted">{item.label}</span>
          <span className="text-dark text-end">{item.value}</span>
        </li>
      ))}
    </ul>
  );

  const cardList = (items: { primary: string; secondary: string; icon: string; tint: string }[]) => (
    <>
      {items.map((item) => (
        <div className="d-flex align-items-center gap-2 border rounded p-2 mb-2" key={item.primary}>
          <span className={`avatar avatar-sm bg-${item.tint}-transparent text-${item.tint} rounded flex-shrink-0`}>
            <i className={item.icon} />
          </span>
          <div className="flex-fill overflow-hidden">
            <h6 className="fs-13 mb-0 text-truncate">{item.primary}</h6>
            <span className="fs-12 text-muted">{item.secondary}</span>
          </div>
        </div>
      ))}
    </>
  );

  const renderDetail = (row: TaxReport) => (
    <div className="row g-4">
      <div className="col-12 col-xl-3 col-md-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-report-money text-primary me-1" />Tax Summary</h6>
        {infoList(row.summary)}
      </div>
      <div className="col-12 col-xl-3 col-md-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-percentage text-warning me-1" />Tax Breakdown</h6>
        {infoList(row.breakdown)}
      </div>
      <div className="col-12 col-xl-3 col-md-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-shield-check text-success me-1" />Filing Information</h6>
        {infoList(row.filing)}
      </div>
      <div className="col-12 col-xl-3 col-md-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-file-invoice text-info me-1" />Included Transactions</h6>
        {cardList(row.transactions.map((item) => ({
          primary: item.label, secondary: item.meta, icon: 'ti ti-file-invoice', tint: 'info',
        })))}
      </div>
      <div className="col-12 col-xl-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-file-text text-purple me-1" />Export History</h6>
        {cardList(row.exports.map((item) => ({
          primary: item.name, secondary: item.meta, icon: 'ti ti-file-text', tint: 'purple',
        })))}
      </div>
      <div className="col-12 col-xl-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-note text-muted me-1" />Internal Notes</h6>
        <p className="fs-13 text-muted mb-2">{row.notes}</p>
        <div className="d-flex flex-wrap gap-2">
          <button type="button" className="btn btn-sm btn-outline-light bg-white" onClick={() => openModal(row, 'view')}>
            <i className="ti ti-eye me-1" />View Report
          </button>
          <button type="button" className="btn btn-sm btn-outline-light bg-white" onClick={() => openModal(row, 'statement')}>
            <i className="ti ti-download me-1" />Tax Statement
          </button>
          <button type="button" className="btn btn-sm btn-outline-light bg-white" onClick={() => setPanelRow(row)}>
            <i className="ti ti-layout-sidebar-right-expand me-1" />Details Panel
          </button>
        </div>
      </div>
    </div>
  );

  /** The eight generator cards above the grid. */
  const catalogue = (
    <div className="row g-3 mb-3">
      {taxReportCards.map((card) => (
        <div className="col-xl-3 col-lg-4 col-md-6" key={card.id}>
          <div className="card mb-0 h-100">
            <div className="card-body p-3 d-flex flex-column">
              <div className="d-flex align-items-center mb-2">
                <span className={`avatar avatar-md bg-${card.tint}-transparent text-${card.tint} rounded me-2 flex-shrink-0`}>
                  <i className={card.icon} />
                </span>
                <div className="overflow-hidden">
                  <h6 className="fs-14 mb-0 text-truncate">{card.label}</h6>
                  <span className="fs-12 text-muted">{card.period}</span>
                </div>
              </div>
              <h5 className="mb-3">{card.value}</h5>
              <button
                type="button"
                className="btn btn-outline-light bg-white btn-sm w-100 d-inline-flex align-items-center justify-content-center mt-auto"
                onClick={() => openModal(null, 'generate')}
              >
                <i className="ti ti-report me-1" />Generate
              </button>
            </div>
          </div>
        </div>
      ))}
    </div>
  );

  return (
    <>
      <div className="page-wrapper">
        <div className="content">
          <PageHeader
            title="Tax Reports"
            section="Accounts"
            dashboardTo={routes.adminDashboard}
            actions={
              <>
                <button
                  type="button"
                  className="btn btn-outline-light bg-white fw-medium d-inline-flex align-items-center me-2 mb-2"
                  onClick={() => openModal(null, 'print')}
                >
                  <i className="ti ti-printer me-2" />Print
                </button>
                <button
                  type="button"
                  className="btn btn-outline-light bg-white fw-medium d-inline-flex align-items-center me-2 mb-2"
                  onClick={() => openModal(null, 'export')}
                >
                  <i className="ti ti-file-export me-2" />Export
                </button>
                <button
                  type="button"
                  className="btn btn-primary d-flex align-items-center mb-2"
                  onClick={() => openModal(null, 'generate')}
                >
                  <i className="ti ti-square-rounded-plus me-2" />Generate Report
                </button>
              </>
            }
          />

          <WorkspaceShell
            workspace={workspace}
            columns={columns}
            getId={(row) => row.id}
            totalCount={rows.length}
            searchPlaceholder="Search tax report or period…"
            searchLabel="Search tax reports"
            savedViews={savedViews}
            filterFields={filterFields}
            quickFilters={quickFilters}
            sortOptions={sortOptions}
            noun="tax reports"
            openMenu={openMenu}
            onOpenMenu={setOpenMenu}
            onRefresh={() => { setRows(initialRows); push('Tax reports refreshed'); }}
            onSaveView={() => push('Current view saved')}
            onToast={push}
            renderDetail={renderDetail}
            renderActions={rowActions}
            emptyIcon="ti ti-percentage"
            emptyTitle="No Tax Reports Found"
            emptyBody="No tax report matches the selected filters."
            emptyAction={
              <button type="button" className="btn btn-primary" onClick={() => openModal(null, 'generate')}>
                <i className="ti ti-square-rounded-plus me-1" />Generate Report
              </button>
            }
            beforeWorkspace={catalogue}
          />

          <Offcanvas
            open={panelRow !== null}
            onClose={() => setPanelRow(null)}
            title="Tax Report Details"
            labelledById="tx_panel_lbl"
          >
            {panelRow ? (
              <>
                <div className="d-flex align-items-center gap-2 pb-3 mb-3 border-bottom">
                  <span className={`avatar avatar-lg bg-${panelRow.taxTypeTint}-transparent text-${panelRow.taxTypeTint} rounded flex-shrink-0`}>
                    <i className="ti ti-file-text" />
                  </span>
                  <div className="overflow-hidden">
                    <h6 className="mb-0 text-truncate">{panelRow.name}</h6>
                    <span className="fs-12 text-muted">{panelRow.filingPeriod}</span>
                  </div>
                  <span className={`dt-pill ${statusPill[panelRow.status]} ms-auto flex-shrink-0`}>
                    <span className="dt-pill-dot" />{panelRow.status}
                  </span>
                </div>
                <div className="border rounded p-3 mb-3 d-flex justify-content-between align-items-center">
                  <span className="fw-medium">Tax Amount</span>
                  <h5 className="mb-0">{money(panelRow.taxAmount)}</h5>
                </div>
                <h6 className="fs-13 mb-2">Tax Summary</h6>
                {infoList(panelRow.summary)}
                <h6 className="fs-13 mb-2 mt-3">Filing Information</h6>
                {infoList(panelRow.filing)}
                {panelRow.status === 'Pending Filing' || panelRow.status === 'Overdue' ? (
                  <button
                    type="button"
                    className="btn btn-primary w-100 mt-3"
                    onClick={() => { const r = panelRow; setPanelRow(null); openModal(r, 'file'); }}
                  >
                    <i className="ti ti-shield-check me-1" />Mark as Filed
                  </button>
                ) : null}
              </>
            ) : null}
          </Offcanvas>
        </div>
      </div>

      {/* Modals */}
      <Modal
        open={activeModal === 'generate'}
        onClose={() => setActiveModal(null)}
        title="Generate Tax Report"
        dialogClassName="modal-lg"
        onSubmit={(e) => { e.preventDefault(); setActiveModal(null); push(`${generateType} report queued`); }}
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={() => setActiveModal(null)}>Cancel</button>
            <button type="submit" className="btn btn-primary">Generate Report</button>
          </>
        }
      >
        <div className="row">
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="tx-type">Tax Type</label>
            <select className="form-select" id="tx-type" value={generateType} onChange={(e) => setGenerateType(e.target.value)}>
              {taxTypeOptions.map((option) => <option key={option}>{option}</option>)}
            </select>
          </div></div>
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="tx-form">Return Form</label>
            <select className="form-select" id="tx-form" value={generateForm} onChange={(e) => setGenerateForm(e.target.value)}>
              {returnFormOptions.map((option) => <option key={option}>{option}</option>)}
            </select>
          </div></div>
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="tx-year">Financial Year</label>
            <select className="form-select" id="tx-year" defaultValue={financialYearOptions[0]}>
              {financialYearOptions.map((option) => <option key={option}>{option}</option>)}
            </select>
          </div></div>
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="tx-period">Filing Period</label>
            <select className="form-select" id="tx-period" defaultValue={filingPeriodOptions[0]}>
              {filingPeriodOptions.map((option) => <option key={option}>{option}</option>)}
            </select>
          </div></div>
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="tx-from">Date From</label>
            <input type="text" className="form-control" id="tx-from" placeholder="01-07-2026" />
          </div></div>
          <div className="col-md-6"><div className="mb-0">
            <label className="form-label" htmlFor="tx-to">Date To</label>
            <input type="text" className="form-control" id="tx-to" placeholder="31-07-2026" />
          </div></div>
        </div>
      </Modal>

      <Modal
        open={activeModal === 'view' && modalRow !== null}
        onClose={() => setActiveModal(null)}
        title="View Tax Report"
        dialogClassName="modal-lg"
        footer={<button type="button" className="btn btn-light" onClick={() => setActiveModal(null)}>Close</button>}
      >
        {modalRow ? (
          <>
            <div className="d-flex align-items-center mb-3 pb-3 border-bottom">
              <span className={`avatar avatar-lg bg-${modalRow.taxTypeTint}-transparent text-${modalRow.taxTypeTint} rounded me-3 flex-shrink-0`}>
                <i className="ti ti-file-text" />
              </span>
              <div>
                <div className="d-flex align-items-center gap-2 flex-wrap">
                  <h5 className="mb-0">{modalRow.name}</h5>
                  <span className={`badge badge-soft-${modalRow.taxTypeTint}`}>{modalRow.taxType}</span>
                  <span className={statusBadge[modalRow.status]}>{modalRow.status}</span>
                </div>
                <p className="mb-0 text-muted fs-13">
                  {modalRow.filingPeriod} · {modalRow.returnForm} · {money(modalRow.taxAmount)}
                </p>
              </div>
            </div>
            <div className="row g-4">
              <div className="col-md-4"><h6 className="fs-14 mb-3">Tax Summary</h6>{infoList(modalRow.summary)}</div>
              <div className="col-md-4"><h6 className="fs-14 mb-3">Tax Breakdown</h6>{infoList(modalRow.breakdown)}</div>
              <div className="col-md-4"><h6 className="fs-14 mb-3">Filing Information</h6>{infoList(modalRow.filing)}</div>
            </div>
          </>
        ) : null}
      </Modal>

      <Modal
        open={activeModal === 'file' && modalRow !== null}
        onClose={() => setActiveModal(null)}
        title="Mark Return as Filed"
        onSubmit={(e) => { e.preventDefault(); markFiled(); }}
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={() => setActiveModal(null)}>Cancel</button>
            <button type="submit" className="btn btn-success"><i className="ti ti-shield-check me-1" />Mark as Filed</button>
          </>
        }
      >
        <p className="fs-13 mb-3">
          Record <span className="fw-medium">{modalRow?.returnForm}</span> for{' '}
          <span className="fw-medium">{modalRow?.name}</span> as filed.
        </p>
        <div className="mb-0">
          <label className="form-label" htmlFor="tx-ack">Acknowledgement Number</label>
          <input
            type="text"
            className="form-control"
            id="tx-ack"
            placeholder="AA290726000000X"
            value={ackNumber}
            onChange={(e) => setAckNumber(e.target.value)}
          />
        </div>
      </Modal>

      <Modal
        open={activeModal === 'export'}
        onClose={() => setActiveModal(null)}
        title="Export Report"
        onSubmit={(e) => { e.preventDefault(); setActiveModal(null); push(`Exported as ${exportFormat}`); }}
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={() => setActiveModal(null)}>Cancel</button>
            <button type="submit" className="btn btn-primary"><i className="ti ti-download me-1" />Export</button>
          </>
        }
      >
        {modalRow ? <p className="fs-13 mb-3">Export <span className="fw-medium">{modalRow.name}</span>.</p> : null}
        <div className="mb-0">
          <label className="form-label" htmlFor="tx-export-format">Format</label>
          <select
            className="form-select"
            id="tx-export-format"
            value={exportFormat}
            onChange={(e) => setExportFormat(e.target.value)}
          >
            <option>PDF</option>
            <option>Excel</option>
            <option>CSV</option>
          </select>
        </div>
      </Modal>

      <Modal
        open={activeModal === 'statement' && modalRow !== null}
        onClose={() => setActiveModal(null)}
        title="Download Tax Statement"
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={() => setActiveModal(null)}>Close</button>
            <button
              type="button"
              className="btn btn-primary"
              onClick={() => { setActiveModal(null); push('Tax statement downloaded'); }}
            >
              <i className="ti ti-download me-1" />Download
            </button>
          </>
        }
      >
        {modalRow ? (
          <>
            {infoList([
              { label: 'Report', value: modalRow.name },
              { label: 'Return Form', value: modalRow.returnForm },
              { label: 'Period', value: modalRow.filingPeriod },
              { label: 'Tax Amount', value: money(modalRow.taxAmount) },
            ])}
            <h6 className="fs-13 mb-2 mt-3">Available Files</h6>
            {cardList(modalRow.exports.map((item) => ({
              primary: item.name, secondary: item.meta, icon: 'ti ti-file-text', tint: 'purple',
            })))}
          </>
        ) : null}
      </Modal>

      <Modal
        open={activeModal === 'print'}
        onClose={() => setActiveModal(null)}
        title="Print Report"
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={() => setActiveModal(null)}>Close</button>
            <button type="button" className="btn btn-primary" onClick={() => { window.print(); setActiveModal(null); }}>
              <i className="ti ti-printer me-1" />Print
            </button>
          </>
        }
      >
        {modalRow ? (
          infoList([
            { label: 'Report', value: modalRow.name },
            { label: 'Tax Type', value: modalRow.taxType },
            { label: 'Period', value: modalRow.filingPeriod },
            { label: 'Tax Amount', value: money(modalRow.taxAmount) },
            { label: 'Status', value: modalRow.status },
          ])
        ) : (
          <p className="fs-13 text-muted mb-0">
            Prints the {workspace.visible.length} tax reports currently listed, with the active filters applied.
          </p>
        )}
      </Modal>

      <ToastStack toasts={toasts} onDismiss={dismiss} id="txToasts" />
    </>
  );
};

export default TaxReports;
