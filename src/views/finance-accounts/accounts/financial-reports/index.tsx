import { Fragment, useCallback, useMemo, useState } from 'react';
import Modal from '@components/ui/Modal';
import Offcanvas from '@components/ui/Offcanvas';
import ToastStack from '@components/ui/ToastStack';
import { ActionLink, PageHeader, WorkspaceShell, useWorkspace } from '@components/workspace';
import type {
  ColumnDef, FilterField, QuickFilter, SavedView, SortOption, WorkspaceMenu,
} from '@components/workspace';
import { all_routes } from '@/routes/all_routes';
import { useToasts } from '@hooks/useToasts';
import type { FinancialReport, ReportFormat, ReportStatus } from './data/financialReports.data';
import {
  departmentOptions, financialReports as initialRows, financialYearOptions, formatIcon,
  formatOptions, generatedByOptions, reportTypeOptions, reportTypes, statusBadge, statusOptions,
  statusPill,
} from './data/financialReports.data';

const routes = all_routes;

/**
 * Financial Year and the two Period fields open pre-applied — the template
 * renders both chips on load. Reset clears them for good.
 */
const filterFields: FilterField[] = [
  { id: 'report-type', label: 'Report Type', kind: 'select', chipLabel: 'Type', options: reportTypeOptions },
  { id: 'financial-year', label: 'Financial Year', kind: 'select', chipLabel: 'Financial Year', options: financialYearOptions, initialValue: '2026 – 2027' },
  { id: 'department', label: 'Department', kind: 'select', chipLabel: 'Dept', options: departmentOptions },
  { id: 'status', label: 'Status', kind: 'select', chipLabel: 'Status', options: statusOptions },
  { id: 'format', label: 'Format', kind: 'select', chipLabel: 'Format', options: formatOptions },
  { id: 'generated-by', label: 'Generated By', kind: 'select', chipLabel: 'By', options: generatedByOptions },
  { id: 'period-from', label: 'Period From', kind: 'date', chipLabel: 'From', placeholder: '01-04-2026' },
  { id: 'period-to', label: 'Period To', kind: 'date', chipLabel: 'To', placeholder: '31-07-2026' },
];

/** Counts are the template's school-wide figures across 126 reports. */
const savedViews: SavedView[] = [
  { id: 'all', label: 'All Reports', icon: 'ti ti-layout-list', count: 126 },
  { id: 'Ready', label: 'Ready to Download', icon: 'ti ti-checks', count: 94 },
  { id: 'Scheduled', label: 'Scheduled Reports', icon: 'ti ti-calendar-repeat', count: 18 },
  { id: 'Failed', label: 'Failed Runs', icon: 'ti ti-alert-triangle', count: 3 },
  { id: 'Archived', label: 'Archived', icon: 'ti ti-folder', count: 11 },
];

const quickFilters: QuickFilter[] = [
  { id: 'Ready', label: 'Ready', icon: 'ti ti-checks', count: 94 },
  { id: 'Generating', label: 'Generating', icon: 'ti ti-clock', count: 2 },
  { id: 'Scheduled', label: 'Scheduled', icon: 'ti ti-calendar-repeat', count: 18 },
  { id: 'Failed', label: 'Failed', icon: 'ti ti-alert-triangle', count: 3 },
  { id: 'Archived', label: 'Archived', icon: 'ti ti-folder', count: 11 },
];

const sortOptions: SortOption[] = [
  { id: 'generated', label: 'Generated on (newest)', icon: 'ti ti-clock' },
  { id: 'name', label: 'Report name (A–Z)', icon: 'ti ti-abc' },
  { id: 'category', label: 'Category', icon: 'ti ti-category' },
  { id: 'status', label: 'Status', icon: 'ti ti-checks' },
  { id: 'format', label: 'Format', icon: 'ti ti-file-text' },
];

type ReportModalId = 'generate' | 'schedule' | 'view' | 'export' | 'print';

/** Sorts "30 Jul 2026" newest-first without a date library. */
const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const dateKey = (value: string): number => {
  const [day, month, year] = value.split(' ');
  const index = months.indexOf(month);
  if (index === -1) return 0;
  return Number(year) * 10000 + (index + 1) * 100 + Number(day);
};

const FinancialReports = () => {
  const [rows, setRows] = useState<FinancialReport[]>(initialRows);
  const [openMenu, setOpenMenu] = useState<WorkspaceMenu>(null);
  const [activeModal, setActiveModal] = useState<ReportModalId | null>(null);
  const [modalRow, setModalRow] = useState<FinancialReport | null>(null);
  const [panelRow, setPanelRow] = useState<FinancialReport | null>(null);
  const [activeCard, setActiveCard] = useState<string | null>(null);
  const [generateType, setGenerateType] = useState(reportTypeOptions[0]);
  const [generateFormat, setGenerateFormat] = useState<ReportFormat>('PDF');
  const [scheduleEvery, setScheduleEvery] = useState('Monthly');
  const [exportFormat, setExportFormat] = useState<ReportFormat>('PDF');

  const { toasts, push, dismiss } = useToasts();

  const openModal = useCallback((row: FinancialReport | null, modal: ReportModalId) => {
    setModalRow(row);
    setActiveModal(modal);
    if (row) setExportFormat(row.format);
  }, []);

  const columns = useMemo<ColumnDef<FinancialReport>[]>(
    () => [
      {
        id: 'name', label: 'Report Name', toggleable: false, sortable: true,
        render: (row) => (
          <div className="dt-user">
            <span className={`avatar avatar-sm bg-${row.categoryTint}-transparent text-${row.categoryTint} rounded me-2 flex-shrink-0`}>
              <i className="ti ti-file-text" />
            </span>
            <div>
              <ActionLink className="dt-name" onClick={() => openModal(row, 'view')}>{row.name}</ActionLink>
              <div className="dt-sub">{row.period}</div>
            </div>
          </div>
        ),
      },
      {
        id: 'category', label: 'Category', sortable: true,
        render: (row) => <span className={`badge badge-soft-${row.categoryTint}`}>{row.category}</span>,
      },
      { id: 'period', label: 'Financial Period', cellClassName: 'fs-13', render: (row) => row.period },
      {
        id: 'generatedBy', label: 'Generated By',
        render: (row) => (
          <>
            <span className="d-block fs-13 fw-medium">{row.generatedBy}</span>
            <span className="fs-12 text-muted">{row.generatedByDept}</span>
          </>
        ),
      },
      {
        id: 'generatedOn', label: 'Generated On', sortable: true, cellClassName: 'fs-13',
        render: (row) => (
          <>
            {row.generatedOn}
            <span className="d-block fs-12 text-muted">{row.generatedAt}</span>
          </>
        ),
      },
      {
        id: 'format', label: 'Format', sortable: true,
        render: (row) => (
          <span className="d-inline-flex align-items-center fs-13">
            <i className={`${formatIcon[row.format]} me-1`} />{row.format}
          </span>
        ),
      },
      {
        id: 'status', label: 'Status', toggleable: false, sortable: true,
        render: (row) => (
          <span className={`dt-pill ${statusPill[row.status]}`}>
            <span className="dt-pill-dot" />{row.status}
          </span>
        ),
      },
      { id: 'lastUpdated', label: 'Last Updated', cellClassName: 'fs-13 text-muted', render: (row) => row.lastUpdated },
    ],
    [openModal],
  );

  const workspace = useWorkspace<FinancialReport>({
    rows, filterFields, columns,
    getId: (row) => row.id,
    search: (row, term) => `${row.name} ${row.category}`.toLowerCase().includes(term),
    matches: (row, filters) => {
      if (filters['report-type'] && row.category !== filters['report-type']) return false;
      if (filters.department && row.generatedByDept !== filters.department) return false;
      if (filters.status && row.status !== filters.status) return false;
      if (filters.format && row.format !== filters.format) return false;
      if (filters['generated-by'] && row.generatedBy !== filters['generated-by']) return false;
      // Financial Year narrows on the row's own "Financial Year" detail line,
      // which not every report carries — those without one always pass.
      const year = filters['financial-year'];
      if (year) {
        const line = row.filters.find((item) => item.label === 'Financial Year');
        if (line && line.value !== year) return false;
      }
      if (activeCard && row.category !== activeCard) return false;
      return true;
    },
    quickMatch: (row, quick) => !quick || row.status === quick,
    viewMatch: (row, view) => (view === 'all' ? true : row.status === view),
    compare: (a, b, sort) => {
      switch (sort) {
        case 'name': return a.name.localeCompare(b.name);
        case 'category': return a.category.localeCompare(b.category) || a.name.localeCompare(b.name);
        case 'status': return a.status.localeCompare(b.status) || a.name.localeCompare(b.name);
        case 'format': return a.format.localeCompare(b.format) || a.name.localeCompare(b.name);
        case 'generated':
        default: return dateKey(b.generatedOn) - dateKey(a.generatedOn) || a.name.localeCompare(b.name);
      }
    },
    defaultSort: 'generated',
    pageSize: 8,
  });

  /* --------------------------------- Actions -------------------------------- */

  const setStatus = useCallback(
    (id: string, status: ReportStatus, extra?: Partial<FinancialReport>) => {
      setRows((current) => current.map((row) => (row.id === id ? { ...row, status, ...extra } : row)));
    },
    [],
  );

  const generate = useCallback(() => {
    const type = reportTypes.find((item) => item.label === generateType) ?? reportTypes[0];
    const created: FinancialReport = {
      id: `rp_new_${rows.length + 1}`,
      name: `${type.label} Statement`,
      period: '01 Apr – 31 Jul 2026',
      category: type.label,
      categoryTint: type.tint,
      generatedBy: 'Finance Manager',
      generatedByDept: 'Accounts',
      generatedOn: '30 Jul 2026',
      generatedAt: '06:40 PM',
      format: generateFormat,
      status: 'Generating',
      lastUpdated: '30 Jul 2026',
      summary: [
        { label: 'Report Type', value: type.label },
        { label: 'Requested By', value: 'Finance Manager' },
        { label: 'Output Format', value: generateFormat },
        { label: 'Stage', value: 'Queued for extract' },
      ],
      filters: [
        { label: 'Financial Year', value: '2026 – 2027' },
        { label: 'Period', value: '01 Apr – 31 Jul 2026' },
        { label: 'Department', value: 'All' },
        { label: 'Cost Centre', value: 'All' },
      ],
      accounts: [],
      files: [],
      schedule: 'Not scheduled · run on demand',
      notes: 'Queued from the Generate Report dialog; the extract runs on the next scheduler tick.',
    };
    setRows((current) => [created, ...current]);
    setActiveModal(null);
    push(`${type.label} queued for generation`);
  }, [generateFormat, generateType, push, rows.length]);

  const rowActions = (row: FinancialReport) => (
    <div className="dt-actions">
      <ActionLink className="dt-ib" ariaLabel="View report" onClick={() => openModal(row, 'view')}>
        <i className="ti ti-eye" />
      </ActionLink>
      <ActionLink className="dt-ib success" ariaLabel="Export report" onClick={() => openModal(row, 'export')}>
        <i className="ti ti-download" />
      </ActionLink>
      <ActionLink className="dt-ib" ariaLabel="Print report" onClick={() => openModal(row, 'print')}>
        <i className="ti ti-printer" />
      </ActionLink>
      <ActionLink className="dt-ib" ariaLabel="Schedule report" onClick={() => openModal(row, 'schedule')}>
        <i className="ti ti-calendar-repeat" />
      </ActionLink>
    </div>
  );

  /* --------------------------------- Panels --------------------------------- */

  const infoList = (items: { label: string; value: string }[]) => (
    <ul className="list-unstyled mb-0">
      {items.map((item, index) => (
        <li
          className={`d-flex justify-content-between py-1 fs-13${index === items.length - 1 ? '' : ' border-bottom'}`}
          key={item.label}
        >
          <span className="text-muted">{item.label}</span>
          <span className="text-dark text-end">{item.value}</span>
        </li>
      ))}
    </ul>
  );

  const renderDetail = (row: FinancialReport) => (
    <div className="row g-4">
      <div className="col-12 col-xl-3 col-md-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-report text-primary me-1" />Report Summary</h6>
        {infoList(row.summary)}
      </div>
      <div className="col-12 col-xl-3 col-md-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-adjustments-horizontal text-info me-1" />Report Filters</h6>
        {infoList(row.filters)}
      </div>
      <div className="col-12 col-xl-3 col-md-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-book text-purple me-1" />Included Accounts</h6>
        {row.accounts.length === 0 ? (
          <p className="fs-13 text-muted mb-0">No accounts resolved yet.</p>
        ) : (
          row.accounts.map((account) => (
            <div className="d-flex align-items-center gap-2 border rounded p-2 mb-2" key={account.code}>
              <span className="avatar avatar-sm bg-primary-transparent text-primary rounded flex-shrink-0">
                <i className="ti ti-book" />
              </span>
              <div className="flex-fill overflow-hidden">
                <h6 className="fs-13 mb-0 text-truncate">{account.name}</h6>
                <span className="fs-12 text-muted">{account.code}</span>
              </div>
            </div>
          ))
        )}
      </div>
      <div className="col-12 col-xl-3 col-md-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-file-text text-success me-1" />Generated Files</h6>
        {row.files.length === 0 ? (
          <p className="fs-13 text-muted mb-0">Nothing generated yet.</p>
        ) : (
          row.files.map((file) => (
            <div className="d-flex align-items-center gap-2 border rounded p-2 mb-2" key={file.name}>
              <span className="avatar avatar-sm bg-info-transparent text-info rounded flex-shrink-0">
                <i className="ti ti-file-text" />
              </span>
              <div className="flex-fill overflow-hidden">
                <h6 className="fs-13 mb-0 text-truncate">{file.name}</h6>
                <span className="fs-12 text-muted">{file.meta}</span>
              </div>
              {file.available ? (
                <ActionLink className="dt-ib" ariaLabel="Download" onClick={() => push(`${file.name} downloaded`)}>
                  <i className="ti ti-download" />
                </ActionLink>
              ) : null}
            </div>
          ))
        )}
      </div>
      <div className="col-12 col-xl-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-calendar-repeat text-warning me-1" />Scheduled Reports</h6>
        <p className="fs-13 text-muted mb-0">{row.schedule}</p>
      </div>
      <div className="col-12 col-xl-6">
        <h6 className="fs-14 mb-3"><i className="ti ti-note text-muted me-1" />Notes</h6>
        <p className="fs-13 text-muted mb-2">{row.notes}</p>
        <div className="d-flex flex-wrap gap-2">
          {row.status === 'Failed' ? (
            <button
              type="button"
              className="btn btn-sm btn-outline-danger"
              onClick={() => { setStatus(row.id, 'Generating'); push(`${row.name} re-queued`); }}
            >
              <i className="ti ti-refresh me-1" />Re-generate
            </button>
          ) : (
            <button type="button" className="btn btn-sm btn-outline-light bg-white" onClick={() => openModal(row, 'view')}>
              <i className="ti ti-eye me-1" />View Report
            </button>
          )}
          <button type="button" className="btn btn-sm btn-outline-light bg-white" onClick={() => openModal(row, 'export')}>
            <i className="ti ti-download me-1" />Export
          </button>
          <button type="button" className="btn btn-sm btn-outline-light bg-white" onClick={() => setPanelRow(row)}>
            <i className="ti ti-layout-sidebar-right-expand me-1" />Preview Panel
          </button>
        </div>
      </div>
    </div>
  );

  /** The eight catalogue cards; clicking one filters the grid to its category. */
  const catalogue = (
    <div className="row g-3 mb-3">
      {reportTypes.map((type) => (
        <div className="col-xl-3 col-lg-4 col-md-6" key={type.id}>
          <div className={`card mb-0 h-100${activeCard === type.id ? ' border-primary' : ''}`}>
            <div className="card-body p-3 d-flex flex-column">
              <div className="d-flex align-items-center mb-2">
                <span className={`avatar avatar-md bg-${type.tint}-transparent text-${type.tint} rounded me-2 flex-shrink-0`}>
                  <i className={type.icon} />
                </span>
                <div className="overflow-hidden">
                  <h6 className="fs-14 mb-0 text-truncate">{type.label}</h6>
                  <span className="fs-12 text-muted">Financial Statement</span>
                </div>
              </div>
              <p className="fs-13 text-muted mb-3">{type.blurb}</p>
              <div className="d-flex align-items-center justify-content-between mt-auto mb-2">
                <span className="fs-12 text-muted">Last generated</span>
                <span className="fs-12 fw-medium">{type.lastGenerated}</span>
              </div>
              <div className="d-flex gap-2">
                <button
                  type="button"
                  className="btn btn-outline-light bg-white btn-sm w-100 d-inline-flex align-items-center justify-content-center"
                  onClick={() => { setGenerateType(type.label); openModal(null, 'generate'); }}
                >
                  <i className="ti ti-report me-1" />Quick Generate
                </button>
                <button
                  type="button"
                  className={`btn btn-sm flex-shrink-0${activeCard === type.id ? ' btn-primary' : ' btn-outline-light bg-white'}`}
                  aria-label={`Filter grid to ${type.label}`}
                  aria-pressed={activeCard === type.id}
                  onClick={() => setActiveCard((current) => (current === type.id ? null : type.id))}
                >
                  <i className="ti ti-filter" />
                </button>
              </div>
            </div>
          </div>
        </div>
      ))}
    </div>
  );

  return (
    <>
      <div className="page-wrapper">
        <div className="content">
          <PageHeader
            title="Financial Reports"
            section="Accounts"
            dashboardTo={routes.adminDashboard}
            actions={
              <>
                <button
                  type="button"
                  className="btn btn-outline-light bg-white fw-medium d-inline-flex align-items-center me-2 mb-2"
                  onClick={() => openModal(null, 'print')}
                >
                  <i className="ti ti-printer me-2" />Print
                </button>
                <button
                  type="button"
                  className="btn btn-outline-light bg-white fw-medium d-inline-flex align-items-center me-2 mb-2"
                  onClick={() => openModal(null, 'export')}
                >
                  <i className="ti ti-file-export me-2" />Export
                </button>
                <button
                  type="button"
                  className="btn btn-primary d-flex align-items-center mb-2"
                  onClick={() => openModal(null, 'generate')}
                >
                  <i className="ti ti-square-rounded-plus me-2" />Generate Report
                </button>
              </>
            }
          />

          <WorkspaceShell
            workspace={workspace}
            columns={columns}
            getId={(row) => row.id}
            totalCount={rows.length}
            searchPlaceholder="Search report name or category…"
            searchLabel="Search reports"
            savedViews={savedViews}
            filterFields={filterFields}
            quickFilters={quickFilters}
            sortOptions={sortOptions}
            noun="reports"
            openMenu={openMenu}
            onOpenMenu={setOpenMenu}
            onRefresh={() => { setRows(initialRows); push('Reports refreshed'); }}
            onSaveView={() => push('Current view saved')}
            onToast={push}
            onResetExtra={() => setActiveCard(null)}
            renderDetail={renderDetail}
            renderActions={rowActions}
            emptyIcon="ti ti-report"
            emptyTitle="No Reports Found"
            emptyBody="No generated report matches the selected filters."
            emptyAction={
              <button type="button" className="btn btn-primary" onClick={() => openModal(null, 'generate')}>
                <i className="ti ti-square-rounded-plus me-1" />Generate Report
              </button>
            }
            beforeWorkspace={catalogue}
          />

          <Offcanvas
            open={panelRow !== null}
            onClose={() => setPanelRow(null)}
            title="Report Preview"
            labelledById="fr_panel_lbl"
          >
            {panelRow ? (
              <>
                <div className="d-flex align-items-center gap-2 pb-3 mb-3 border-bottom">
                  <span className={`avatar avatar-lg bg-${panelRow.categoryTint}-transparent text-${panelRow.categoryTint} rounded flex-shrink-0`}>
                    <i className="ti ti-file-text" />
                  </span>
                  <div className="overflow-hidden">
                    <h6 className="mb-0 text-truncate">{panelRow.name}</h6>
                    <span className="fs-12 text-muted">{panelRow.period}</span>
                  </div>
                  <span className={`dt-pill ${statusPill[panelRow.status]} ms-auto flex-shrink-0`}>
                    <span className="dt-pill-dot" />{panelRow.status}
                  </span>
                </div>
                <h6 className="fs-13 mb-2">Report Summary</h6>
                {infoList(panelRow.summary)}
                <h6 className="fs-13 mb-2 mt-3">Report Filters</h6>
                {infoList(panelRow.filters)}
                <h6 className="fs-13 mb-2 mt-3">Generated Files</h6>
                {panelRow.files.length === 0 ? (
                  <p className="fs-13 text-muted mb-0">Nothing generated yet.</p>
                ) : (
                  panelRow.files.map((file) => (
                    <div className="d-flex align-items-center gap-2 border rounded p-2 mb-2" key={file.name}>
                      <div className="flex-fill overflow-hidden">
                        <h6 className="fs-13 mb-0 text-truncate">{file.name}</h6>
                        <span className="fs-12 text-muted">{file.meta}</span>
                      </div>
                    </div>
                  ))
                )}
                <button
                  type="button"
                  className="btn btn-primary w-100 mt-3"
                  onClick={() => { const r = panelRow; setPanelRow(null); openModal(r, 'export'); }}
                >
                  <i className="ti ti-download me-1" />Export Report
                </button>
              </>
            ) : null}
          </Offcanvas>
        </div>
      </div>

      {/* Modals */}
      <Modal
        open={activeModal === 'generate'}
        onClose={() => setActiveModal(null)}
        title="Generate Report"
        dialogClassName="modal-lg"
        onSubmit={(e) => { e.preventDefault(); generate(); }}
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={() => setActiveModal(null)}>Cancel</button>
            <button type="submit" className="btn btn-primary">Generate Report</button>
          </>
        }
      >
        <div className="row">
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="fr-type">Report Type</label>
            <select className="form-select" id="fr-type" value={generateType} onChange={(e) => setGenerateType(e.target.value)}>
              {reportTypeOptions.map((option) => <option key={option}>{option}</option>)}
            </select>
          </div></div>
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="fr-year">Financial Year</label>
            <select className="form-select" id="fr-year" defaultValue={financialYearOptions[0]}>
              {financialYearOptions.map((option) => <option key={option}>{option}</option>)}
            </select>
          </div></div>
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="fr-from">Period From</label>
            <input type="text" className="form-control" id="fr-from" placeholder="01-04-2026" />
          </div></div>
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="fr-to">Period To</label>
            <input type="text" className="form-control" id="fr-to" placeholder="31-07-2026" />
          </div></div>
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="fr-dept">Department</label>
            <select className="form-select" id="fr-dept" defaultValue={departmentOptions[0]}>
              {departmentOptions.map((option) => <option key={option}>{option}</option>)}
            </select>
          </div></div>
          <div className="col-md-6"><div className="mb-0">
            <label className="form-label" htmlFor="fr-format">Output Format</label>
            <select
              className="form-select"
              id="fr-format"
              value={generateFormat}
              onChange={(e) => setGenerateFormat(e.target.value as ReportFormat)}
            >
              {formatOptions.map((option) => <option key={option}>{option}</option>)}
            </select>
          </div></div>
        </div>
      </Modal>

      <Modal
        open={activeModal === 'schedule'}
        onClose={() => setActiveModal(null)}
        title="Schedule Report"
        onSubmit={(e) => {
          e.preventDefault();
          if (modalRow) {
            setStatus(modalRow.id, modalRow.status, { schedule: `${scheduleEvery} · next run pending` });
          }
          setActiveModal(null);
          push('Report schedule saved');
        }}
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={() => setActiveModal(null)}>Cancel</button>
            <button type="submit" className="btn btn-primary">Save Schedule</button>
          </>
        }
      >
        {modalRow ? <p className="fs-13 mb-3">Schedule <span className="fw-medium">{modalRow.name}</span>.</p> : null}
        <div className="row">
          <div className="col-md-6"><div className="mb-3">
            <label className="form-label" htmlFor="fr-every">Frequency</label>
            <select className="form-select" id="fr-every" value={scheduleEvery} onChange={(e) => setScheduleEvery(e.target.value)}>
              <option>Daily</option>
              <option>Weekly</option>
              <option>Monthly</option>
              <option>Quarterly</option>
            </select>
          </div></div>
          <div className="col-md-6"><div className="mb-0">
            <label className="form-label" htmlFor="fr-time">Run Time</label>
            <input type="text" className="form-control" id="fr-time" placeholder="06:00 AM" />
          </div></div>
        </div>
      </Modal>

      <Modal
        open={activeModal === 'view' && modalRow !== null}
        onClose={() => setActiveModal(null)}
        title="View Report"
        dialogClassName="modal-lg"
        footer={<button type="button" className="btn btn-light" onClick={() => setActiveModal(null)}>Close</button>}
      >
        {modalRow ? (
          <>
            <div className="d-flex align-items-center mb-3 pb-3 border-bottom">
              <span className={`avatar avatar-lg bg-${modalRow.categoryTint}-transparent text-${modalRow.categoryTint} rounded me-3 flex-shrink-0`}>
                <i className="ti ti-file-text" />
              </span>
              <div>
                <div className="d-flex align-items-center gap-2 flex-wrap">
                  <h5 className="mb-0">{modalRow.name}</h5>
                  <span className={`badge badge-soft-${modalRow.categoryTint}`}>{modalRow.category}</span>
                  <span className={statusBadge[modalRow.status]}>{modalRow.status}</span>
                </div>
                <p className="mb-0 text-muted fs-13">
                  {modalRow.period} · generated {modalRow.generatedOn} at {modalRow.generatedAt}
                </p>
              </div>
            </div>
            <div className="row g-4">
              <div className="col-md-6">
                <h6 className="fs-14 mb-3">Report Summary</h6>
                {infoList(modalRow.summary)}
              </div>
              <div className="col-md-6">
                <h6 className="fs-14 mb-3">Report Filters</h6>
                {infoList(modalRow.filters)}
              </div>
              <div className="col-12">
                <h6 className="fs-14 mb-3">Included Accounts</h6>
                <div className="d-flex flex-wrap gap-2">
                  {modalRow.accounts.map((account) => (
                    <Fragment key={account.code}>
                      <span className="badge badge-soft-secondary">{account.name} · {account.code}</span>
                    </Fragment>
                  ))}
                </div>
              </div>
            </div>
          </>
        ) : null}
      </Modal>

      <Modal
        open={activeModal === 'export'}
        onClose={() => setActiveModal(null)}
        title="Export Report"
        onSubmit={(e) => {
          e.preventDefault();
          setActiveModal(null);
          push(`Exported as ${exportFormat}`);
        }}
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={() => setActiveModal(null)}>Cancel</button>
            <button type="submit" className="btn btn-primary"><i className="ti ti-download me-1" />Export</button>
          </>
        }
      >
        {modalRow ? <p className="fs-13 mb-3">Export <span className="fw-medium">{modalRow.name}</span>.</p> : null}
        <div className="mb-0">
          <label className="form-label" htmlFor="fr-export-format">Format</label>
          <select
            className="form-select"
            id="fr-export-format"
            value={exportFormat}
            onChange={(e) => setExportFormat(e.target.value as ReportFormat)}
          >
            {formatOptions.map((option) => <option key={option}>{option}</option>)}
          </select>
        </div>
      </Modal>

      <Modal
        open={activeModal === 'print'}
        onClose={() => setActiveModal(null)}
        title="Print Report"
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={() => setActiveModal(null)}>Close</button>
            <button type="button" className="btn btn-primary" onClick={() => { window.print(); setActiveModal(null); }}>
              <i className="ti ti-printer me-1" />Print
            </button>
          </>
        }
      >
        {modalRow ? (
          infoList([
            { label: 'Report', value: modalRow.name },
            { label: 'Category', value: modalRow.category },
            { label: 'Period', value: modalRow.period },
            { label: 'Format', value: modalRow.format },
            { label: 'Status', value: modalRow.status },
          ])
        ) : (
          <p className="fs-13 text-muted mb-0">
            Prints the {workspace.visible.length} reports currently listed, with the active filters applied.
          </p>
        )}
      </Modal>

      <ToastStack toasts={toasts} onDismiss={dismiss} id="frToasts" />
    </>
  );
};

export default FinancialReports;
