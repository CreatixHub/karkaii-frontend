import { useEffect, useState } from 'react';
import Modal from '@components/ui/Modal';
import ImageWithBasePath from '@core/common/imageWithBasePath';
import type { Payslip } from '../data/payslips.data';
import {
  deductionComponents,
  earningComponents,
  money,
  netSalary,
  statusBadge,
} from '../data/payslips.data';

export type PayslipModalId =
  | 'payroll_details'
  | 'salary_breakdown'
  | 'earnings_deductions'
  | 'email_payslip'
  | 'payroll_history'
  | 'delete';

export interface PayslipModalsProps {
  active: PayslipModalId | null;
  row: Payslip | null;
  onClose: () => void;
  onToast: (message: string) => void;
  onConfirmDelete: () => void;
}

const Identity = ({ row, subtitle }: { row: Payslip; subtitle: string }) => (
  <div className="d-flex align-items-center mb-3 pb-3 border-bottom">
    <span className="avatar avatar-lg me-3">
      <ImageWithBasePath src={row.avatar} className="rounded" alt={row.name} />
    </span>
    <div>
      <div className="d-flex align-items-center gap-2">
        <h5 className="mb-0">{row.name}</h5>
        <span className="badge bg-primary-transparent text-primary">{row.id}</span>
        <span className={statusBadge[row.status]}>{row.status}</span>
      </div>
      <p className="mb-0 text-muted fs-13">{subtitle}</p>
    </div>
  </div>
);

const AmountRows = ({ items, total }: { items: { label: string; amount: number }[]; total: { label: string; value: number } }) => (
  <>
    {items.map((item) => (
      <div className="d-flex align-items-center justify-content-between mb-2" key={item.label}>
        <span className="fs-13 text-muted">{item.label}</span>
        <span className="fs-13 fw-medium">{money(item.amount)}</span>
      </div>
    ))}
    <div className="d-flex align-items-center justify-content-between border-top pt-2 mt-2">
      <span className="fs-13 fw-medium">{total.label}</span>
      <span className="fs-13 fw-medium">{money(total.value)}</span>
    </div>
  </>
);

const PayslipModals = ({ active, row, onClose, onToast, onConfirmDelete }: PayslipModalsProps) => {
  const [email, setEmail] = useState('');
  const [subject, setSubject] = useState('');
  const [message, setMessage] = useState('');

  useEffect(() => {
    if (active === 'email_payslip' && row) {
      setEmail(`${row.name.toLowerCase().replace(/\s+/g, '.')}@school.edu`);
      setSubject(`Payslip for ${row.month}`);
      setMessage(`Dear ${row.name.split(' ')[0]}, please find your payslip for ${row.month} attached.`);
    }
  }, [active, row]);

  const closeFooter = (extra?: React.ReactNode) => (
    <>
      <button type="button" className="btn btn-light me-2" onClick={onClose}>
        Close
      </button>
      {extra}
    </>
  );

  const subtitle = row ? `${row.designation} · ${row.department} · ${row.month}` : '';

  return (
    <>
      {/* Payroll Details */}
      <Modal
        open={active === 'payroll_details' && row !== null}
        onClose={onClose}
        title="Payroll Details"
        dialogClassName="modal-lg"
        footer={closeFooter()}
      >
        {row ? (
          <>
            <Identity row={row} subtitle={subtitle} />
            <div className="row">
              <div className="col-md-6">
                <ul className="list-unstyled mb-0">
                  {[
                    { label: 'Payroll Month', value: row.month },
                    { label: 'Basic Salary', value: money(row.basic) },
                    { label: 'Allowances', value: `+${money(row.allowances)}` },
                    { label: 'Deductions', value: `−${money(row.deductions)}` },
                  ].map((item, index, arr) => (
                    <li
                      className={`d-flex justify-content-between py-1 fs-13${index === arr.length - 1 ? '' : ' border-bottom'}`}
                      key={item.label}
                    >
                      <span className="text-muted">{item.label}</span>
                      <span className="text-dark">{item.value}</span>
                    </li>
                  ))}
                </ul>
              </div>
              <div className="col-md-6">
                <ul className="list-unstyled mb-0">
                  {[
                    { label: 'Net Salary', value: money(netSalary(row)) },
                    { label: 'Payment Method', value: row.method.label },
                    { label: 'Payment Date', value: row.paymentDate },
                    { label: 'Generated By', value: row.generatedBy },
                  ].map((item, index, arr) => (
                    <li
                      className={`d-flex justify-content-between py-1 fs-13${index === arr.length - 1 ? '' : ' border-bottom'}`}
                      key={item.label}
                    >
                      <span className="text-muted">{item.label}</span>
                      <span className="text-dark">{item.value}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </div>
          </>
        ) : null}
      </Modal>

      {/* Salary Breakdown */}
      <Modal
        open={active === 'salary_breakdown' && row !== null}
        onClose={onClose}
        title="Salary Breakdown"
        dialogClassName="modal-lg"
        footer={closeFooter(
          <button
            type="button"
            className="btn btn-primary"
            onClick={() => {
              onToast('Payslip download started');
              onClose();
            }}
          >
            <i className="ti ti-download me-1" />
            Download
          </button>,
        )}
      >
        {row ? (
          <>
            <Identity row={row} subtitle={subtitle} />
            <div className="row g-3 mb-3">
              {[
                { label: 'Basic', value: money(row.basic) },
                { label: 'Allowances', value: `+${money(row.allowances)}` },
                { label: 'Deductions', value: `−${money(row.deductions)}` },
                { label: 'Net Salary', value: money(netSalary(row)) },
              ].map((tile) => (
                <div className="col-6 col-md-3" key={tile.label}>
                  <div className="border rounded p-3 text-center h-100">
                    <p className="fs-12 text-muted mb-1">{tile.label}</p>
                    <h6 className="mb-0">{tile.value}</h6>
                  </div>
                </div>
              ))}
            </div>
          </>
        ) : null}
      </Modal>

      {/* Earnings & Deductions */}
      <Modal
        open={active === 'earnings_deductions' && row !== null}
        onClose={onClose}
        title="Earnings &amp; Deductions"
        dialogClassName="modal-lg"
        footer={closeFooter()}
      >
        {row ? (
          <>
            <Identity row={row} subtitle={subtitle} />
            <div className="row g-4">
              <div className="col-md-6">
                <h6 className="fs-14 mb-3">
                  <i className="ti ti-trending-up text-success me-1" />
                  Earnings
                </h6>
                <AmountRows
                  items={earningComponents(row)}
                  total={{ label: 'Gross', value: row.basic + row.allowances }}
                />
              </div>
              <div className="col-md-6">
                <h6 className="fs-14 mb-3">
                  <i className="ti ti-trending-down text-danger me-1" />
                  Deductions
                </h6>
                <AmountRows
                  items={deductionComponents(row)}
                  total={{ label: 'Net Salary', value: netSalary(row) }}
                />
              </div>
            </div>
          </>
        ) : null}
      </Modal>

      {/* Email Payslip */}
      <Modal
        open={active === 'email_payslip' && row !== null}
        onClose={onClose}
        title="Email Payslip"
        onSubmit={(event) => {
          event.preventDefault();
          onToast(`Payslip emailed to ${email}`);
          onClose();
        }}
        footer={
          <>
            <button type="button" className="btn btn-light me-2" onClick={onClose}>
              Cancel
            </button>
            <button type="submit" className="btn btn-primary">
              <i className="ti ti-send me-1" />
              Send
            </button>
          </>
        }
      >
        <div className="mb-3">
          <label className="form-label" htmlFor="payslip-email">
            Recipient
          </label>
          <input
            type="email"
            className="form-control"
            id="payslip-email"
            value={email}
            onChange={(event) => setEmail(event.target.value)}
          />
        </div>
        <div className="mb-3">
          <label className="form-label" htmlFor="payslip-subject">
            Subject
          </label>
          <input
            type="text"
            className="form-control"
            id="payslip-subject"
            value={subject}
            onChange={(event) => setSubject(event.target.value)}
          />
        </div>
        <div className="mb-0">
          <label className="form-label" htmlFor="payslip-message">
            Message
          </label>
          <textarea
            className="form-control"
            rows={3}
            id="payslip-message"
            value={message}
            onChange={(event) => setMessage(event.target.value)}
          />
        </div>
      </Modal>

      {/* Payroll History */}
      <Modal
        open={active === 'payroll_history' && row !== null}
        onClose={onClose}
        title="Payroll History"
        dialogClassName="modal-lg"
        footer={closeFooter(
          <button
            type="button"
            className="btn btn-primary"
            onClick={() => {
              onToast('Payroll history export started');
              onClose();
            }}
          >
            <i className="ti ti-download me-1" />
            Export
          </button>,
        )}
      >
        {row ? (
          <>
            <Identity row={row} subtitle={`${row.id} · ${row.designation}`} />
            <div className="table-responsive">
              <table className="table table-hover align-middle mb-0">
                <thead className="table-light">
                  <tr>
                    <th>Month</th>
                    <th>Basic</th>
                    <th>Allowances</th>
                    <th>Deductions</th>
                    <th>Net</th>
                    <th>Status</th>
                  </tr>
                </thead>
                <tbody>
                  {['Jul 2026', 'Jun 2026', 'May 2026', 'Apr 2026'].map((month, index) => {
                    const scale = 1 - index * 0.02;
                    const basic = Math.round(row.basic * scale);
                    const allow = Math.round(row.allowances * scale);
                    const deduct = Math.round(row.deductions * scale);
                    return (
                      <tr key={month}>
                        <td>{month}</td>
                        <td>{money(basic)}</td>
                        <td>{money(allow)}</td>
                        <td>{money(deduct)}</td>
                        <td>{money(basic + allow - deduct)}</td>
                        <td>
                          <span className={index === 0 ? statusBadge[row.status] : 'badge badge-soft-success'}>
                            {index === 0 ? row.status : 'Paid'}
                          </span>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </>
        ) : null}
      </Modal>

      {/* Confirm Deletion */}
      <Modal
        open={active === 'delete'}
        onClose={onClose}
        title="Confirm Deletion"
        hideHeader
        bodyClassName="text-center"
        onSubmit={(event) => {
          event.preventDefault();
          onConfirmDelete();
        }}
      >
        <span className="delete-icon">
          <i className="ti ti-trash-x" />
        </span>
        <h4>Confirm Deletion</h4>
        <p>You want to delete this payslip, this cant be undone once you delete.</p>
        <div className="d-flex justify-content-center">
          <button type="button" className="btn btn-light me-3" onClick={onClose}>
            Cancel
          </button>
          <button type="submit" className="btn btn-danger">
            Yes, Delete
          </button>
        </div>
      </Modal>
    </>
  );
};

export default PayslipModals;
